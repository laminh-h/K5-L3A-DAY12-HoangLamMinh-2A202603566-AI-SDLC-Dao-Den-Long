"""Run every tests/scenarios/<name>/ through the REAL headless CLI (twice), check
expect.json, check byte-identical output, and write evidence to docs/proof/<phase>/.

Usage: python3 tools/run_scenarios.py [--phase phase-1]
Exit code 1 if any scenario fails (so CI / hooks can block).
"""
import argparse
import json
import os
import platform
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCN = os.path.join(ROOT, "tests", "scenarios")


def headless(args):
    return subprocess.run([sys.executable, "-m", "lantern.headless", *args],
                          cwd=ROOT, capture_output=True, text=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", default="phase-2")
    a = ap.parse_args()
    out_dir = os.path.join(ROOT, "docs", "proof", a.phase, "runs")
    os.makedirs(out_dir, exist_ok=True)
    rows, ok_all = [], True
    for name in sorted(os.listdir(SCN)):
        d = os.path.join(SCN, name)
        with open(os.path.join(d, "expect.json"), encoding="utf-8") as f:
            exp = json.load(f)
        args = ["--seed", str(exp["seed"]), "--night", str(exp.get("night", 1)),
                "--ticks", str(exp["ticks"])]
        if os.path.exists(os.path.join(d, "scenario.json")):
            args += ["--scenario", os.path.relpath(os.path.join(d, "scenario.json"), ROOT)]
        args += ["--inputs", os.path.relpath(os.path.join(d, "inputs.json"), ROOT)]
        o1 = os.path.join(out_dir, name + ".jsonl")
        o2 = os.path.join(out_dir, name + ".run2.jsonl")
        t0 = time.perf_counter()
        r1 = headless(args + ["--out", o1])
        dt = time.perf_counter() - t0
        r2 = headless(args + ["--out", o2])
        problems = []
        if r1.returncode != 0 or r2.returncode != 0:
            problems.append("exit %s/%s %s" % (r1.returncode, r2.returncode, r1.stderr.strip()))
        else:
            with open(o1, "rb") as f1, open(o2, "rb") as f2:
                same = f1.read() == f2.read()
            os.remove(o2)
            if not same:
                problems.append("non-deterministic")
            with open(o1, encoding="utf-8") as f:
                lines = [json.loads(l) for l in f]
            end = lines[-1]
            evs = [l["name"] for l in lines if l["type"] == "event"]
            if end.get("type") != "end":
                problems.append("last line is not end")
            if "events" in exp and evs != exp["events"]:
                problems.append("events %s != %s" % (evs, exp["events"]))
            for k in ("state", "score", "ticks"):
                if "end_" + k in exp and end.get(k) != exp["end_" + k]:
                    problems.append("end.%s=%s expected %s" % (k, end.get(k), exp["end_" + k]))
        ok = not problems
        ok_all &= ok
        cmd = "python3 -m lantern.headless " + " ".join(args) + " --out <out>"
        rows.append((name, exp.get("requirement", ""), cmd, "PASS" if ok else "FAIL: " + "; ".join(problems),
                     "%.2fs" % dt))
        print("%-26s %s" % (name, rows[-1][3]))
    md = ["# Scenario results (%s)" % a.phase, "",
          "Generated by `python3 tools/run_scenarios.py --phase %s` — do not edit by hand." % a.phase,
          "", "Machine: %s, Python %s" % (platform.platform(), platform.python_version()), "",
          "Each scenario is run twice through the real CLI; outputs must be byte-identical (determinism).",
          "", "| Scenario | Requirement | Result | Time (1 run) |", "|---|---|---|---|"]
    for n, req, cmd, res, dt in rows:
        md.append("| [%s](runs/%s.jsonl) | %s | %s | %s |" % (n, n, req, res, dt))
    md += ["", "Commands:", ""] + ["- `%s`: `%s`" % (n, cmd) for n, _, cmd, _, _ in rows]
    with open(os.path.join(ROOT, "docs", "proof", a.phase, "scenarios.md"), "w",
              encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md) + "\n")
    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(main())
